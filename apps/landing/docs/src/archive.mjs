/** Folders whose every page belongs to the archive (autogenerated sidebar groups). */
export const ARCHIVE_GROUPS = [
	{ label: 'Handbook', translations: { es: 'Manual' }, directory: 'handbook' },
	{ label: 'Examples', translations: { es: 'Ejemplos' }, directory: 'examples' },
];

/** Whether a Starlight route id (`handbook/commands/run`, `es/faq`...) is a v3 archive page. */
export function isArchivePage(id) {
	const slug = String(id ?? '').replace(/^es(\/|$)/, '').replace(/\/index$/, '');
	if (slug === '') return false;
	return ARCHIVE_PAGES.some((page) => page.slug === slug)
		|| ARCHIVE_GROUPS.some(({ directory }) => slug === directory || slug.startsWith(`${directory}/`));
}
