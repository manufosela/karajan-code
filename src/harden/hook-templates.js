/**
 * Hook bodies + profile→hooks mapping for `kj harden` (KJC-TSK-0555, 0562).
 *
 * A body is the MANAGED portion only; harden-engine adds the shebang and the
 * kj:managed markers around it. Pure POSIX sh — the universal checks (commit
 * format, AI-attribution) need no toolchain, and lint/format/test lines call
 * the project's NATIVE commands (from `cmds`), only when present. No npm/Node
 * is imposed on non-JS repos. See docs/specs/quality-harness.md §5.
 */

// KJC-TSK-1076: exported so the third-party PR checks apply the same rules.
export const CONVENTIONAL_TYPES = "feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert";
export const AI_ATTRIBUTION = "co-authored-by:.*(claude|gpt|copilot|gemini)|(generated|written) (by|with) .*(claude|gpt|copilot)";

export const SHEBANG = "#!/usr/bin/env sh";

/** Hooks enabled per profile. */
export const PROFILE_HOOKS = {
  minimal: ["commit-msg"],
  standard: ["pre-commit", "prepare-commit-msg", "commit-msg", "pre-push", "post-merge"],
  strict: ["pre-commit", "prepare-commit-msg", "commit-msg", "pre-push", "post-merge"],
};

/** Build the managed body for a single hook. */
// KJC-TSK-0645: `core.hooksPath .karajan/hooks` eclipses the user's global
// hooks dir, silently disabling personal guards. Every generated hook ends by
// chaining its namesake in the machine's global dir.
// KJC-BUG-0161 / 0169 (ADR 0009), HU-2762: the dir is looked up when the hook
// RUNS, never when kj harden ran — so the generated bytes do not depend on the
// machine (HOME, GIT_CONFIG_GLOBAL), the provenance verifies in CI, and no
// local filesystem layout leaks into a public repo. `|| true`: the preamble
// sets `set -e`. `--type=path` expands `~`; the pwd -P test stops a hook from
// calling itself when the global setting is this repo's own hooks dir.
function chainToGlobal(hook) {
  // KJC-TSK-1085: pre-push already read the refs from stdin; the chained hook gets them back.
  const call = hook === "pre-push" ? `printf '%s\\n' "$kj_push_refs" | "$kj_global/${hook}" "$@"; rc=$?` : `"$kj_global/${hook}" "$@"; rc=$?`;
  return [
    "# Chain the machine's global hook, looked up when the hook runs, not when kj harden ran (KJC-TSK-0645, HU-2762).",
    "kj_global=$(git config --global --type=path --get core.hooksPath 2>/dev/null || true)",
    `if [ -n "$kj_global" ] && [ -x "$kj_global/${hook}" ] && [ "$(cd "$kj_global" 2>/dev/null && pwd -P)" != "$(cd "$(dirname "$0")" && pwd -P)" ]; then`,
    `  ${call}`,
    '  [ "$rc" -eq 0 ] || exit "$rc"',
    "fi",
  ];
}

// KJC-TSK-0648: branch-first, enforced. The first external session of the
// v4 environment committed on local main following literal instructions —
// the playbook now orders "branch first" and this guard backs it up.
function baseBranchGuard(baseBranch) {
  if (!baseBranch) return [];
  return [
    "# Branch-first guard — the base branch only moves via PR. KJC-BUG-0186:",
    "# the bootstrap commit is exempt, there is no commit to branch from yet.",
    "# No escape (ADR 0015): an env prefix on git commit was one the agent could raise.",
    "if git rev-parse --verify HEAD >/dev/null 2>&1; then",
    '  current_branch=$(git symbolic-ref --short HEAD 2>/dev/null || echo "")',
    `  if [ "$current_branch" = "${baseBranch}" ]; then`,
    `    echo 'kj harden: direct commits on ${baseBranch} are not allowed — create a branch and open a PR'; exit 1`,
    "  fi",
    "fi",
  ];
}

// IDN-C (KJC-TSK-0764, ADR 0005): identity lock at tier B — the declared clone
// identity (.karajan/identity.local.yml) governs authorship on commit and the
// gh session on push, on ANY host. Undeclared = advisory only (old clones keep
// working); the fail-closed default is the Sentinel's (IDN-B).
function identityGuard(hook) {
  const head = [
    "# Identity lock (IDN-C, ADR 0005) — this clone's declared identity governs.",
    "if [ -f .karajan/identity.local.yml ]; then",
  ];
  const tail = [
    "elif [ ! -f .karajan/identity.local.yml ]; then",
    "  echo 'kj harden: no identity declared for this clone — run kj identity set (advisory)'",
    "fi",
  ];
  if (hook === "pre-commit") {
    return [
      ...head,
      "  kj_declared_email=$(sed -n 's/^git_email:[[:space:]]*//p' .karajan/identity.local.yml | head -n1)",
      "  kj_author=$(git var GIT_AUTHOR_IDENT | sed 's/.*<\\(.*\\)>.*/\\1/')",
      "  kj_committer=$(git var GIT_COMMITTER_IDENT | sed 's/.*<\\(.*\\)>.*/\\1/')",
      '  if [ -n "$kj_declared_email" ] && { [ "$kj_author" != "$kj_declared_email" ] || [ "$kj_committer" != "$kj_declared_email" ]; }; then',
      '    echo "kj harden: identity lock — committing as $kj_author / $kj_committer but this clone is declared as $kj_declared_email (kj identity show)"; exit 1',
      "  fi",
      ...tail,
    ];
  }
  return [
    ...head,
    // KJC-TSK-1085: every commit the push brings carries the declared identity
    // (a rebase, cherry-pick, merge or tag never ran pre-commit).
    "  kj_declared_email=$(sed -n 's/^git_email:[[:space:]]*//p' .karajan/identity.local.yml | head -n1)",
    '  if [ -n "$kj_declared_email" ]; then',
    '    printf "%s\\n" "$kj_push_refs" | while read -r kj_lref kj_lsha kj_rref kj_rsha; do',
    '      case "$kj_lsha" in *[!0]*) ;; *) continue ;; esac',
    // A new ref: what the PUSH TARGET ($1, the remote git hands the hook) does not have yet.
    '      case "$kj_rsha" in *[!0]*) kj_new=$(git rev-list "$kj_rsha..$kj_lsha") ;; *) kj_new=$(git rev-list "$kj_lsha" --not --remotes="${1:-origin}") ;; esac',
    "      for kj_c in $kj_new; do",
    '        kj_who=$(git log -1 --format="%ae %ce" "$kj_c")',
    '        if [ "$kj_who" != "$kj_declared_email $kj_declared_email" ]; then',
    '          echo "kj harden: identity lock — commit $(git log -1 --format=%h "$kj_c") is authored/committed as $kj_who but this clone is declared as $kj_declared_email"; exit 1',
    "        fi",
    "      done",
    "    done || exit 1",
    "  fi",
    "  kj_declared_gh=$(sed -n 's/^gh_user:[[:space:]]*//p' .karajan/identity.local.yml | head -n1)",
    '  kj_hosts="${GH_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/gh}/hosts.yml"',
    "  kj_active_gh=$(awk '/^github.com:/{f=1;next} f&&/^[^[:space:]]/{f=0} f&&/^[[:space:]]*user:/{sub(/^[[:space:]]*user:[[:space:]]*/,\"\");print;exit}' \"$kj_hosts\" 2>/dev/null)",
    '  if [ -n "$kj_declared_gh" ] && [ "$kj_active_gh" != "$kj_declared_gh" ]; then',
    '    echo "kj harden: identity lock — gh session is ${kj_active_gh:-none} but this clone is declared as $kj_declared_gh — run: gh auth switch --user $kj_declared_gh"; exit 1',
    "  fi",
    ...tail,
  ];
}

export function hookBody(hook, cmds = {}, { baseBranch = null } = {}) {
  const chain = chainToGlobal(hook);
  switch (hook) {
    case "pre-commit": {
      const lines = [...baseBranchGuard(baseBranch), ...identityGuard("pre-commit"), "# Lint + format the working tree with the project's native tools."];
      if (cmds.lint) lines.push(`${cmds.lint} || { echo 'kj harden: lint failed'; exit 1; }`);
      if (cmds.format) lines.push(`${cmds.format} || { echo 'kj harden: format check failed'; exit 1; }`);
      if (!cmds.lint && !cmds.format) lines.push("# (no lint/format command detected for this stack)");
      lines.push(
        "# KJC-BUG-0164: attribution is surface EVERYWHERE — the staged diff's",
        "# ADDED lines (changelog, docs, code comments) are scanned too, with",
        "# the same precise pattern (tool MENTIONS stay legal; attribution not).",
        "# The guard's own definition files are excluded by literal path — they",
        "# CONTAIN the pattern; excluding a path that does not exist is harmless.",
        "# KJC-BUG-0170: the generated supervisor hooks (.karajan/hooks/pre-commit,",
        "# commit-msg) also CONTAIN the pattern by design — the bootstrap commit",
        "# that versions them must not self-detect in the consumer repo.",
        "# KJC-BUG-0200 (issue #1772): the same is true of .karajan/harness — the",
        "# whole DIRECTORY is excluded, not one file, so a supervisor script added",
        "# later cannot bring the bug back.",
        `if git diff --cached -- . ':(exclude).github/workflows/kj-no-ai-attribution.yml' ':(exclude)src/harden/hook-templates.js' ':(exclude)src/harden/workflow-templates.js' ':(exclude)src/harden/sentinel-hooks.js' ':(exclude)scripts/ai-attribution-guard.yml' ':(exclude)tests/harden/attribution-guard.test.js' ':(exclude)tests/harden/sentinel-hooks.test.js' ':(exclude).karajan/hooks/pre-commit' ':(exclude).karajan/hooks/commit-msg' ':(exclude).karajan/harness/' | grep '^+' | grep -qiE '${AI_ATTRIBUTION}|generated with \\[?claude'; then`,
        "  echo 'kj harden: AI attribution is not allowed in committed content'; exit 1",
        "fi",
        "# KJC-BUG-0296 (issue #1989): the host agent's runtime and local state never",
        "# enter a commit, however they were staged (a blanket `git add -A` put a",
        "# Claude scheduler lock into main). Checked on the staged list itself,",
        "# deletions left out: untracking a runtime file is the fix (KJC-BUG-0307).",
        "if git diff --cached --name-only --diff-filter=d | grep -qE '^(\\.claude/[^/]*\\.lock|\\.claude/scheduled_tasks\\.lock|\\.kj/|\\.karajan/identity\\.local\\.yml|\\.karajan/harness/sentinel-state\\.json)'; then",
        "  echo 'kj harden: agent runtime files are staged (.claude/*.lock, .kj/, identity.local.yml, sentinel-state.json) — unstage them: git restore --staged <path>'; exit 1",
        "fi",
        "# KJC-TSK-1205 (ADR 0030): a tampered Sentinel is caught before each commit,",
        "# not only when the turn ends. Only where it is installed; no kj, no check.",
        "if [ -d .karajan/harness ] && command -v kj >/dev/null 2>&1; then",
        "  kj sentinel verify >/dev/null 2>&1 || { echo 'kj harden: the Sentinel is tampered with (kj sentinel verify says how) — restore it with kj harden'; exit 1; }",
        "fi",
        "# v4 review gate (ENV-C1, opt-in via `kj review --install-gate`):",
        "# a staged diff only enters with a recorded cross-AI approved verdict.",
        "# KJC-BUG-0165: the gate is active once the marker is COMMITTED (HEAD),",
        "# not merely present — so the bootstrap commit that INTRODUCES it is",
        "# exempt (no gate can exist before it does), and it cannot be bypassed",
        "# by deleting the working-tree file.",
        "if git cat-file -e HEAD:.karajan/review-gate 2>/dev/null; then",
        "  if ! command -v kj >/dev/null 2>&1; then",
        "    echo 'kj: review gate is enabled but kj is not installed — see karajancode.com/docs/getting-started/installation'; exit 1",
        "  fi",
        "  kj review --check || { echo 'kj: no approved cross-AI verdict for the staged diff — run `kj review --staged`'; exit 1; }",
        "fi"
      );
      return [...lines, ...chain].join("\n");
    }
    case "commit-msg":
      // Pure POSIX — Conventional Commits header, length cap, AI-attribution.
      return [
        'msg_file="$1"',
        'header=$(head -n1 "$msg_file")',
        `if ! printf '%s' "$header" | grep -qE '^(${CONVENTIONAL_TYPES})(\\([a-z0-9._-]+\\))?!?: .+'; then`,
        "  echo 'kj harden: commit header must follow Conventional Commits (type: subject)'; exit 1",
        "fi",
        'if [ "${#header}" -gt 100 ]; then echo \'kj harden: commit header exceeds 100 chars\'; exit 1; fi',
        "# KJC-TSK-0909: the rest of what CI's commitlint rejects, caught here.",
        "if ! awk 'NR > 2 && !/^#/ && length($0) > 100 { exit 1 }' \"$msg_file\"; then",
        "  echo 'kj harden: a commit body line exceeds 100 chars (CI commitlint rejects it)'; exit 1",
        "fi",
        'if [ -x node_modules/.bin/commitlint ]; then',
        '  node_modules/.bin/commitlint --edit "$msg_file" || exit 1',
        "fi",
        `if grep -qiE '${AI_ATTRIBUTION}' "$msg_file"; then`,
        "  echo 'kj harden: AI attribution is not allowed in commit messages'; exit 1",
        "fi",
        ...chain,
      ].join("\n");
    case "pre-push": {
      const lines = [
        // KJC-TSK-1085: git hands the pushed refs on stdin; kept for the identity check and the chained hook.
        "[ -t 0 ] || kj_push_refs=$(cat)",
        "# Identity guard — never push without a configured git identity.",
        'if [ -z "$(git config user.email)" ] || [ -z "$(git config user.name)" ]; then',
        "  echo 'kj harden: git user.name/user.email not set — refusing to push'; exit 1",
        "fi",
        'echo "kj harden: pushing as $(git config user.name) <$(git config user.email)>"',
        ...identityGuard("pre-push"),
        "# Run the test suite before pushing.",
      ];
      if (cmds.test) lines.push(`${cmds.test} || { echo 'kj harden: tests failed'; exit 1; }`);
      else lines.push("# (no test command detected for this stack)");
      return [...lines, ...chain].join("\n");
    }
    case "prepare-commit-msg":
      // KJC-TSK-0692 (MG-F): the branch already carries the card ref
      // (validated by the card-first gate) — the subject inherits it
      // automatically. A convention that enforces itself needs no adoption.
      return [
        'msg_file="$1"',
        'branch=$(git symbolic-ref --short HEAD 2>/dev/null || echo "")',
        "# POSIX-safe extraction (no grep -o): the ref is the leading",
        "# card-shaped token of the branch's last segment (feat/REF-desc).",
        "seg=$(printf '%s' \"$branch\" | tr '[:upper:]' '[:lower:]'); seg=\"${seg##*/}\"",
        String.raw`ref=$(printf '%s' "$seg" | sed -nE 's/^([a-z][a-z0-9]{1,9}(-[a-z][a-z0-9]{1,9})*-[0-9]{1,6})(-.*)?$/\1/p')`,
        'header=$(head -n1 "$msg_file")',
        'if [ -n "$ref" ] && [ -n "$header" ]; then',
        '  case "$header" in',
        "    Merge*|fixup!*|squash!*) ;;",
        "    *)",
        "      # Boundary match — a header mentioning KJW-TSK-00011 must not",
        "      # suppress the KJW-TSK-0001 stamp. $ref is [a-z0-9-] only by",
        "      # construction (sed extraction above), safe inside the ERE.",
        '      if ! printf \'%s\' "$header" | grep -qiE "(^|[^a-zA-Z0-9-])$ref([^a-zA-Z0-9-]|$)"; then',
        "        stamp=$(printf '%s' \"$ref\" | tr '[:lower:]' '[:upper:]')",
        '        new_header="$header ($stamp)"',
        '        if [ "${#new_header}" -le 100 ]; then',
        String.raw`          { printf '%s\n' "$new_header"; tail -n +2 "$msg_file"; } > "$msg_file.kjtmp" && mv "$msg_file.kjtmp" "$msg_file"`,
        "        fi",
        "      fi",
        "      ;;",
        "  esac",
        "fi",
        ...chain,
      ].join("\n");
    case "post-merge":
      return [
        "# Refresh the local RAG index so retrieval never serves stale code.",
        "# KJC-BUG-0381: detached, so the merge never waits for it (one took 15 minutes),",
        "# and one at a time: a lock in the git dir holding the run's pid, freed only when",
        "# that process is gone (a lock with no pid, after an hour).",
        "if command -v kj >/dev/null 2>&1; then",
        "  kj_git_dir=$(git rev-parse --git-dir 2>/dev/null) || kj_git_dir=.git",
        '  kj_lock="$kj_git_dir/kj-rag-index.lock"',
        '  if [ -d "$kj_lock" ]; then',
        '    kj_pid=$(cat "$kj_lock/pid" 2>/dev/null)',
        '    if [ -n "$kj_pid" ]; then kill -0 "$kj_pid" 2>/dev/null || rm -rf "$kj_lock"',
        '    else find "$kj_lock" -maxdepth 0 -mmin +60 -exec rm -rf {} \\; 2>/dev/null; fi',
        "  fi",
        '  if mkdir "$kj_lock" 2>/dev/null; then',
        '    ( kj rag index --since auto >"$kj_git_dir/kj-rag-index.log" 2>&1; rm -rf "$kj_lock" ) </dev/null >/dev/null 2>&1 &',
        '    echo $! >"$kj_lock/pid" 2>/dev/null',
        "  fi",
        "fi",
        ...chain,
      ].join("\n");
    default:
      throw new Error(`Unknown hook: ${hook}`);
  }
}
